def calculate_confidence_interval(data, confidence=0.95):
    """
    Calcule l'intervalle de confiance pour la moyenne d'une série

    Formule: x̄ ± t(α/2) × (s/√n)
    """
    n = len(data)
    mean = np.mean(data)
    std_err = stats.sem(data)  # Erreur standard de la moyenne
    margin = std_err * t.ppf((1 + confidence) / 2, n - 1)

    return mean, mean - margin, mean + margin, margin

# Calcul des intervalles de confiance pour les variables clés
