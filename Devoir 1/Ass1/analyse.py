for col in vars_cles:
    mean, ci_lower, ci_upper, margin = calculate_confidence_interval(X[col].dropna())
    ic_results.append({
        'Variable': col,
        'Moyenne': mean,
        'IC_Inférieur': ci_lower,
        'IC_Supérieur': ci_upper,
        'Marge_Erreur': margin
    })
    print(f"{col:30s} : {mean:8.3f} ± {margin:.3f}  [{ci_lower:.3f}, {ci_upper:.3f}]")

ic_df = pd.DataFrame(ic_results)

